package com.test.domain.repositories;

/*
  This package contains the repository interfaces for the application.

  Repositories are responsible for providing a way to access and manipulate domain objects without exposing the underlying data storage mechanism.

  Among their responsibilities, repositories typically:
  - Define methods for querying and persisting domain objects
  - Handle data access logic
  - Provide Port (interface only) implemented in infrastructure and linked by DI for interacting with the data layer
 */