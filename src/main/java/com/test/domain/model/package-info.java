/*
  This package contains the domain model classes for the application.

  The domain model represents the core business concepts and rules of the application.
  It encapsulates the state and behavior of the entities, value objects, and aggregates that make up the business domain.

  Among its responsibilities, the domain model typically:
  - Defines Root-Aggregates, Entities, Value-Objects, Domain-Services, Domain-Events, Domain-Exceptions, Factories, etc.
  - Implements business rules and invariants
  - Ensures consistency and integrity of the domain model
 */